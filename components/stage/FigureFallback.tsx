'use client';

import { useEffect, useState } from 'react';

import type { PresetId } from '@/lib/physics/states.mjs';

interface Contour {
  className: 'c-pos' | 'c-neg';
  d: string;
}

interface Figure {
  viewBox: string;
  contours: Contour[];
}

const PATH_DATA = /^[Mml0-9 .-]+$/;
const VIEW_BOX = /^0 0 \d+ \d+$/;

/**
 * Read the generated SVG and keep only what the figure needs (the viewBox and
 * each contour's class and path data), so nothing from the file reaches the
 * DOM except numbers rendered by React.
 */
function parseFigure(text: string): Figure | null {
  const doc = new DOMParser().parseFromString(text, 'image/svg+xml');
  const root = doc.documentElement;
  const viewBox = root.getAttribute('viewBox') ?? '';
  if (root.nodeName !== 'svg' || !VIEW_BOX.test(viewBox)) return null;
  const contours: Contour[] = [];
  for (const path of Array.from(root.getElementsByTagName('path'))) {
    const className = path.getAttribute('class');
    const d = path.getAttribute('d') ?? '';
    if ((className === 'c-pos' || className === 'c-neg') && PATH_DATA.test(d)) contours.push({ className, d });
  }
  return { viewBox, contours };
}

/**
 * The static contour map of a preset (generated by scripts/build-figures.mjs),
 * shown when WebGL is unavailable or lost and in forced-colors mode. CSS
 * colours contours by sign; negative contours are always dashed, so the sign
 * never depends on colour alone.
 */
export default function FigureFallback({ preset }: { preset: PresetId }) {
  const [figure, setFigure] = useState<Figure | null>(null);

  useEffect(() => {
    let alive = true;
    fetch(`/figures/${preset}.svg`)
      .then((response) => (response.ok ? response.text() : Promise.reject(new Error(`HTTP ${response.status}`))))
      .then((text) => {
        if (alive) setFigure(parseFigure(text));
      })
      .catch(() => {
        // The placeholder gradient stays; on a page header or the 404 the caption
        // still describes the figure (the homepage figure is decorative).
      });
    return () => {
      alive = false;
    };
  }, [preset]);

  if (!figure) return null;
  return (
    <div className="figure-fallback">
      <svg viewBox={figure.viewBox} fill="none" stroke="currentColor" strokeWidth={1.25} strokeLinejoin="round" aria-hidden="true" focusable="false">
        {figure.contours.map(({ className, d }, i) => (
          <path key={i} className={className} d={d} strokeDasharray={className === 'c-neg' ? '5 4' : undefined} />
        ))}
      </svg>
    </div>
  );
}
