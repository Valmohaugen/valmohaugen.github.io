// @ts-check
/**
 * Verify lib/motion/spring.mjs: the site's spring easing is the exact step
 * response of an underdamped harmonic oscillator, sampled into CSS linear().
 *
 *   x(t) = 1 − e^{−ζω₀t} [cos(ω_d t) + (ζω₀/ω_d) sin(ω_d t)]
 *   ω₀ = 2π f₀,  ω_d = ω₀ √(1 − ζ²),  0 < ζ < 1
 *
 * Peak: x(t_p) = 1 + exp(−ζπ / √(1 − ζ²)) at t_p = π / ω_d.
 * Limits checked: ζ → 1⁻ has no overshoot; the closed form at every sample.
 * Reference: Ogata, Modern Control Engineering, 5th ed., §5-3 (second-order
 * step response).
 *
 * Also checks that tokens.css carries the generated --ease-spring, so the
 * token can never drift from the physics, and the other motion tokens; that
 * the reduced-motion guard covers view transitions; that the old
 * ScrollReveal and starfield stay gone; the print rules; cubicBezier
 * (bezier.mjs); drawFraction, penLine and revealDelay (scroll.mjs); and that
 * the reveal cleanup waits out --dur-morph.
 */

import assert from 'node:assert/strict';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

import { cubicBezier } from '../lib/motion/bezier.mjs';
import { DRAW_LINE, REVEAL_MAX_STEPS, REVEAL_STAGGER_MS, drawFraction, penLine, revealDelay } from '../lib/motion/scroll.mjs';
import { springEasing } from '../lib/motion/spring.mjs';

const TOL = 1e-3; // values are printed with 4 decimals
let passed = 0;
let failed = 0;
/** @param {string} name @param {() => void} fn */
function check(name, fn) {
  try {
    fn();
    passed += 1;
    console.log(`[ok]   ${name}`);
  } catch (err) {
    failed += 1;
    console.log(`[FAIL] ${name}\n       ${err instanceof Error ? err.message.split('\n')[0] : err}`);
  }
}

/** @param {string} css */
function values(css) {
  assert.match(css, /^linear\(.+\)$/, `not a linear() function: ${css}`);
  return css.slice('linear('.length, -1).split(',').map((s) => Number(s.trim()));
}

/**
 * Closed-form step response (the reference this test trusts).
 * @param {number} t Time in seconds. @param {number} zeta @param {number} f0 Hz
 */
function stepResponse(t, zeta, f0) {
  const w0 = 2 * Math.PI * f0;
  const wd = w0 * Math.sqrt(1 - zeta * zeta);
  return 1 - Math.exp(-zeta * w0 * t) * (Math.cos(wd * t) + ((zeta * w0) / wd) * Math.sin(wd * t));
}

check('linear() with samples + 1 finite values, 0 first, exactly 1 last', () => {
  const v = values(springEasing(0.7, 1.8, 600));
  assert.equal(v.length, 49);
  assert.ok(v.every(Number.isFinite));
  assert.equal(v[0], 0);
  assert.equal(v.at(-1), 1);
});

check('custom sample count', () => {
  assert.equal(values(springEasing(0.7, 1.8, 600, 10)).length, 11);
});

check('matches the closed-form step response at every sample', () => {
  const [zeta, f0, ms, n] = [0.7, 1.8, 600, 48];
  const v = values(springEasing(zeta, f0, ms, n));
  for (let k = 0; k < n; k += 1) {
    const expected = stepResponse((k / n) * (ms / 1000), zeta, f0);
    assert.ok(Math.abs(v[k] - expected) < TOL, `sample ${k}: ${v[k]} vs ${expected}`);
  }
});

check('overshoot equals the analytic peak 1 + exp(−ζπ/√(1−ζ²))', () => {
  const zeta = 0.7;
  const peak = 1 + Math.exp((-zeta * Math.PI) / Math.sqrt(1 - zeta * zeta));
  const v = values(springEasing(zeta, 1.8, 600));
  assert.ok(Math.abs(Math.max(...v) - peak) < TOL, `max ${Math.max(...v)} vs ${peak}`);
});

check('limit ζ → 1⁻: no overshoot', () => {
  const v = values(springEasing(0.999, 1.8, 600));
  assert.ok(Math.max(...v) <= 1 + TOL, `max ${Math.max(...v)}`);
});

check('invalid parameters throw RangeError', () => {
  for (const args of [[0, 1.8, 600], [1, 1.8, 600], [-0.1, 1.8, 600], [0.7, 0, 600], [0.7, 1.8, 0], [0.7, 1.8, 600, 1]]) {
    assert.throws(() => springEasing(.../** @type {[number, number, number, number?]} */ (args)), RangeError, `args ${args}`);
  }
});

check('tokens.css --ease-spring is generated by springEasing(0.7, 1.8, 600)', () => {
  const css = readFileSync(new URL('../assets/css/tokens.css', import.meta.url), 'utf8');
  const m = /--ease-spring:\s*([^;]+);/.exec(css);
  assert.ok(m, '--ease-spring missing from tokens.css');
  assert.equal(m[1].trim(), springEasing(0.7, 1.8, 600));
});

const css = (/** @type {string} */ f) => readFileSync(new URL(`../assets/css/${f}`, import.meta.url), 'utf8');

check('motion tokens carry their designed values', () => {
  const tokens = css('tokens.css');
  const expected = {
    '--ease-measure': 'cubic-bezier(0.2, 0, 0, 1)',
    '--ease-unitary': 'cubic-bezier(0.37, 0, 0.63, 1)',
    '--ease-exit': 'cubic-bezier(0.4, 0, 1, 1)',
    '--dur-press': '120ms',
    '--dur-measure': '200ms',
    '--dur-settle': '360ms',
    '--dur-morph': '600ms',
    '--dur-prepare': '1600ms',
  };
  for (const [name, value] of Object.entries(expected)) {
    const m = new RegExp(`${name}:\\s*([^;]+);`).exec(tokens);
    assert.ok(m, `${name} missing`);
    assert.equal(m[1].trim(), value, name);
  }
});

check('the reduced-motion guard covers view transitions', () => {
  const motion = css('motion.css');
  assert.match(motion, /@media \(prefers-reduced-motion: reduce\)[\s\S]*::view-transition-group\(\*\)/);
});

check('the old ScrollReveal component and starfield stay gone (scroll effects live in ScrollEffects.tsx)', () => {
  /** @param {string} dir @returns {string[]} */
  const files = (dir) => readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? files(p) : /\.(tsx?|css)$/.test(n) ? [p] : [];
  });
  const offenders = ['app', 'components', 'lib', 'assets/css'].flatMap(files).filter((f) =>
    /reveal-init|ScrollReveal|StarfieldAccent|starfield/.test(readFileSync(f, 'utf8')));
  assert.deepEqual(offenders, []);
});

check('print: figures, overlays and cats are hidden (a WebGL canvas can print as a blank box)', () => {
  const print = css('print.css');
  const hidden = print.match(/([^{}]+)\{\s*display:\s*none\s*!important;?\s*\}/g)?.join(' ') ?? '';
  for (const selector of ['.route-figure', '.hero-stage', '.hero-cat', '.cat', '.decrypt__overlay', '.link-decrypt', '.timeline-item::after']) {
    assert.ok(hidden.includes(selector), `print.css does not hide ${selector}`);
  }
});

check('cubicBezier: endpoints, monotone, CSS ease(0.5) ≈ 0.8024, linear identity', () => {
  const ease = cubicBezier(0.25, 0.1, 0.25, 1);
  assert.equal(ease(0), 0);
  assert.equal(ease(1), 1);
  assert.ok(Math.abs(ease(0.5) - 0.8024033877399112) < 1e-6, `ease(0.5) = ${ease(0.5)}`);
  const linear = cubicBezier(0, 0, 1, 1);
  for (const x of [0.1, 0.37, 0.9]) assert.ok(Math.abs(linear(x) - x) < 1e-9);
  const prepare = cubicBezier(0.16, 1, 0.3, 1);
  let last = 0;
  for (let x = 0; x <= 1; x += 0.01) {
    const y = prepare(x);
    assert.ok(y >= last - 1e-12 && y <= 1 + 1e-12, `not monotone at ${x}`);
    last = y;
  }
});

check('drawFraction: 0 below the pen, 1 above it, linear between, non-decreasing as the page scrolls', () => {
  const line = 700 * DRAW_LINE;
  assert.equal(drawFraction(line, 200, line), 0);
  assert.equal(drawFraction(line + 50, 200, line), 0);
  assert.equal(drawFraction(line - 200, 200, line), 1);
  assert.equal(drawFraction(line - 500, 200, line), 1);
  assert.ok(Math.abs(drawFraction(line - 50, 200, line) - 0.25) < 1e-12);
  // Zero height: drawn exactly once its top has passed the pen.
  assert.equal(drawFraction(line + 1, 0, line), 0);
  assert.equal(drawFraction(line, 0, line), 1);
  let last = -1;
  for (let top = 900; top >= -400; top -= 7) {
    const f = drawFraction(top, 260, line);
    assert.ok(f >= last && f >= 0 && f <= 1, `not monotone or out of range at top = ${top}`);
    last = f;
  }
});

check('penLine: rests at DRAW_LINE·h, reaches the bottom edge at the end of the page, continuous and non-decreasing', () => {
  const h = 1000;
  const g = h * (1 - DRAW_LINE);
  /** @param {number} a @param {number} b */
  const near = (a, b) => assert.ok(Math.abs(a - b) < 1e-9, `${a} ≠ ${b}`);
  near(penLine(h, 0, 5000), h * DRAW_LINE);
  near(penLine(h, 5000 - g, 5000), h * DRAW_LINE);
  near(penLine(h, 5000, 5000), h);
  near(penLine(h, 0, 0), h);
  near(penLine(h, 5000 - g / 2, 5000), h * DRAW_LINE + g / 2);
  let last = -Infinity;
  for (let y = 0; y <= 5000; y += 3) {
    const line = penLine(h, y, 5000);
    assert.ok(line >= last - 1e-9 && line >= h * DRAW_LINE - 1e-9 && line <= h + 1e-9, `not monotone or out of range at y = ${y}`);
    // The pen never moves faster than the page scrolls (no jump).
    assert.ok(last === -Infinity || line - last <= 3 + 1e-9, `jumps at y = ${y}`);
    last = line;
  }
});

check('revealDelay: steps of REVEAL_STAGGER_MS, capped at REVEAL_MAX_STEPS, never negative', () => {
  assert.equal(revealDelay(0), 0);
  assert.equal(revealDelay(1), REVEAL_STAGGER_MS);
  assert.equal(revealDelay(REVEAL_MAX_STEPS + 5), REVEAL_MAX_STEPS * REVEAL_STAGGER_MS);
  assert.equal(revealDelay(-3), 0);
});

check('scroll reveals: the cleanup waits out --dur-morph, and print shows blocks still waiting', () => {
  const morph = Number(css('tokens.css').match(/--dur-morph:\s*(\d+)ms/)?.[1]);
  const source = readFileSync(new URL('../components/ScrollEffects.tsx', import.meta.url), 'utf8');
  const wait = Number(source.match(/const REVEAL_MS = (\d+) \+ \d+;/)?.[1]);
  assert.equal(wait, morph, `ScrollEffects waits ${wait} ms; --dur-morph is ${morph} ms`);
  assert.match(css('print.css'), /\.fx-pending,\s*\.fx-pending > \*\s*\{\s*opacity: 1 !important;/);
});

if (failed) {
  console.log(`[FAIL] verify-motion: ${failed} failed, ${passed} passed`);
  process.exitCode = 1;
} else {
  console.log(`[done] verify-motion: ${passed} checks passed`);
}
